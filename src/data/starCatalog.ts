/**
 * Converts astronomical Right Ascension (hours), Declination (deg), and distance (ly)
 * into right-handed 3D Cartesian coordinates (Y-up = North Celestial Pole, X = Vernal Equinox).
 */
export function equatorialToCartesian(
  raHours: number,
  decDeg: number,
  distance: number,
): [number, number, number] {
  const raRad = (raHours / 24) * Math.PI * 2;
  const decRad = (decDeg * Math.PI) / 180;
  const cosDec = Math.cos(decRad);
  const x = distance * cosDec * Math.cos(raRad);
  const y = distance * Math.sin(decRad);
  const z = -distance * cosDec * Math.sin(raRad);
  return [x, y, z];
}

export function parseLuminositySolar(lumStr: string): number {
  const cleaned = lumStr.replace(/,/g, '');
  const val = Number.parseFloat(cleaned);
  return Number.isFinite(val) && val > 0 ? val : 1;
}

/**
 * Estimates stellar photosphere radius in Solar radii (R☉) via Stefan-Boltzmann law:
 * R / R☉ = sqrt(L / L☉) * (5778 / T_eff)^2
 */
export function getStarSolarRadius(star: NearbyStarData): number {
  if (star.components && star.components.length > 0) {
    const primary = star.components.find((c) => !c.isVirtualBarycenter);
    if (primary) return getStarComponentSolarRadius(primary);
  }
  const lum = parseLuminositySolar(star.luminositySolar);
  const tempRatio = 5778 / Math.max(star.temperatureK, 1500);
  const radiusSolar = Math.sqrt(lum) * tempRatio * tempRatio;
  return Math.max(0.08, Math.min(radiusSolar, 1500));
}

export function getStarComponentSolarRadius(comp: StarComponentData): number {
  if (typeof comp.radiusSolar === 'number' && comp.radiusSolar > 0) {
    return comp.radiusSolar;
  }
  const tempRatio = 5778 / Math.max(comp.temperatureK, 1500);
  const radiusSolar = Math.sqrt(Math.max(comp.luminositySolar, 1e-6)) * tempRatio * tempRatio;
  return Math.max(0.008, Math.min(radiusSolar, 1500));
}


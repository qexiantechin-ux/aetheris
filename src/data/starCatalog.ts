export function kelvinToBlackbodySrgb(tempK: number): [number, number, number] {
  const t = Math.max(1800, Math.min(tempK, 40000)) / 100;
  let r: number;
  let g: number;
  let b: number;

  if (t <= 66) {
    r = 1;
    g = Math.max(0, Math.min(1, (99.4708025861 * Math.log(t) - 161.1195681661) / 255));
    b =
      t <= 19
        ? 0
        : Math.max(0, Math.min(1, (138.5177312231 * Math.log(t - 10) - 305.0447927307) / 255));
  } else {
    r = Math.max(0, Math.min(1, (329.698727446 * Math.pow(t - 60, -0.1332047592)) / 255));
    g = Math.max(0, Math.min(1, (288.1221695283 * Math.pow(t - 60, -0.0755148492)) / 255));
    b = 1;
  }

  return [r, g, b];
}

export function kelvinToStarHex(tempK: number): string {
  const [r, g, b] = kelvinToBlackbodySrgb(tempK);
  const toHex = (v: number) =>
    Math.round(Math.max(0, Math.min(1, v)) * 255)
      .toString(16)
      .padStart(2, '0');
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}


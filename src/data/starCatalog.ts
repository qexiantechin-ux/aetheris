interface ConstellationStarSeed {
  id: string;
  name: string;
  designation: string;
  spectralClass: string;
  spectralGroup: NearbyStarData['spectralGroup'];
  raHours: number;
  decDeg: number;
  distanceLy: number;
  apparentMag: number;
  absoluteMag: number;
  luminositySolar: string;
  temperatureK: number;
  constellation: string;
  summary: string;
  components?: StarComponentData[];
  overviewSpanAu?: number;
}

function makeConstellationStar(s: ConstellationStarSeed): NearbyStarData {
  return {
    id: s.id,
    name: s.name,
    designation: s.designation,
    spectralClass: s.spectralClass,
    spectralGroup: s.spectralGroup,
    color: kelvinToStarHex(s.temperatureK),
    raHours: s.raHours,
    decDeg: s.decDeg,
    distanceLy: s.distanceLy,
    apparentMag: s.apparentMag,
    absoluteMag: s.absoluteMag,
    luminositySolar: s.luminositySolar,
    temperatureK: s.temperatureK,
    constellation: s.constellation,
    exoplanetsCount: 0,
    summary: s.summary,
    highlights: [
      `Main star of ${s.constellation} located ${s.distanceLy.toLocaleString()} light-years from Sol.`,
      `True blackbody photosphere temperature ~${s.temperatureK.toLocaleString()} K (${s.spectralClass}).`,
    ],
    components: s.components,
    overviewSpanAu: s.overviewSpanAu,
  };
}

